import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const fixed = [
  'agent/system/identity.md', 'agent/system/rules.md', 'agent/system/workflow.md',
  'agent/system/output_style.md', 'agent/system/boundaries.md', 'agent/system/mode_router.md',
  'agent/system/sales_boundaries.md',
]
const byMode = {
  student_reply: ['agent/knowledge/student_segmentation.md', 'agent/knowledge/resume_analysis.md', 'agent/knowledge/career_direction.md', 'agent/examples/01_resume_diagnosis.md', 'agent/examples/04_non_core_opening.md'],
  product_consultation: ['agent/knowledge/products.md', 'agent/knowledge/pricing.md', 'agent/knowledge/internship_services.md', 'agent/knowledge/career_coaching.md', 'agent/knowledge/fulltime_job_matching.md', 'agent/knowledge/aftersales_rules.md', 'agent/examples/05_process_price_fit.md', 'agent/examples/08_internship_matching.md', 'agent/examples/11_aftersales_handoff.md', 'agent/examples/12_pricing_response.md'],
  career_script: ['agent/knowledge/student_segmentation.md', 'agent/knowledge/resume_analysis.md', 'agent/knowledge/career_direction.md', 'agent/knowledge/global_education_and_roles.md', 'agent/knowledge/call_diagnostic.md', 'agent/knowledge/career_coaching.md', 'agent/examples/02_phone_script.md', 'agent/examples/03_make_it_oral.md', 'agent/examples/07_resume_service_transition.md'],
}
const forbidden = [/migration[\\/]/i, /INTERNAL_RESTRICTED_KNOWLEDGE/i, /MIGRATION_REPORT/i, /SECOND_STAGE_REVIEW/i, /deprecated_facts/i, /DeepSeek API Key/i, /DEEPSEEK_API_KEY\\s*=[^\\s#]/i]
const pii = [/(?<!\d)1[3-9]\d{9}(?!\d)/, /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/, /wxid_[A-Za-z0-9_-]+/]

const files = {}
for (const file of [...new Set([...fixed, ...Object.values(byMode).flat()])]) {
  if (!file.startsWith('agent/system/') && !file.startsWith('agent/knowledge/') && !file.startsWith('agent/examples/')) throw new Error(`运行时白名单路径非法：${file}`)
  const text = await fs.readFile(path.join(root, file), 'utf8')
  if (forbidden.some((pattern) => pattern.test(text)) || pii.some((pattern) => pattern.test(text))) throw new Error(`运行时知识包含禁止内容：${file}`)
  files[file] = text
}
const productPath = path.join(root, 'agent', 'knowledge', 'public-product-config.json')
const productConfig = JSON.parse(await fs.readFile(productPath, 'utf8'))
const productText = JSON.stringify(productConfig)
if (forbidden.some((pattern) => pattern.test(productText)) || pii.some((pattern) => pattern.test(productText))) throw new Error('产品配置包含禁止内容')

const generated = `// Generated by scripts/build-runtime-knowledge.mjs. Do not edit manually.\nexport default ${JSON.stringify({ fixed, byMode, files, productConfig }, null, 2)} as const\n`
const outputDir = path.join(root, 'functions', '_generated')
await fs.mkdir(outputDir, { recursive: true })
await fs.writeFile(path.join(outputDir, 'runtime-knowledge.ts'), generated, 'utf8')
console.log(`runtime knowledge built: ${Object.keys(files).length} files`)
